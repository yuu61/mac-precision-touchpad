//! Serves `HidBth`'s SDP attribute search with the augmented HID descriptor.
//!
//! At start, `HidBth` reads the HID service's attributes with `IOCTL_BTH_SDP_SERVICE_ATTRIBUTE_SEARCH`
//! twice: first with a 9-byte output buffer to learn `requiredSize`, then with a buffer of that size
//! (seen on hardware: 9 bytes, then 280). Both calls arrive at `PASSIVE_LEVEL`.
//!
//! For each call this filter sends the same search down with its own large buffer, appends the
//! vendor collection with [`augment_sdp_attribute_list`], and answers `HidBth` itself, so both calls
//! report the same, exact size. Anything unexpected (another IRQL, a failed or oversized search, an
//! attribute list it cannot change) forwards the original request unchanged instead.

use core::ffi::c_void;
use core::ptr::null_mut;

use amtptp_hidfilter_core::bth::{SdpAugmentError, augment_sdp_attribute_list};
use tracelogging as tlg;
use wdf_support::init::{memory_descriptor_init_buffer, sync_send_options};
use wdf_support::ntstatus::{NT_SUCCESS, STATUS_SUCCESS};
use wdk_sys::ntddk::{ExAllocatePool2, ExFreePoolWithTag, KeGetCurrentIrql};
use wdk_sys::{
    NTSTATUS, PASSIVE_LEVEL, PVOID, ULONG, ULONG_PTR, WDFDEVICE, WDFREQUEST,
    call_unsafe_wdf_function_binding,
};

use crate::{KW_SDP, PROVIDER};

/// `IOCTL_BTH_SDP_SERVICE_ATTRIBUTE_SEARCH` (`METHOD_BUFFERED`).
pub(crate) const IOCTL_SDP_SERVICE_ATTRIBUTE_SEARCH: u32 = 0x0041_0210;

/// `BTH_SDP_STREAM_RESPONSE` header: `requiredSize` and `responseSize` (both ULONG).
const STREAM_HEADER_LEN: usize = 8;
/// The largest attribute list served (the Magic Trackpad 2's is 271 bytes).
const MAX_STREAM_LEN: usize = 4096;
/// One scratch buffer: a stream response with up to [`MAX_STREAM_LEN`] bytes.
const SCRATCH_LEN: usize = STREAM_HEADER_LEN + MAX_STREAM_LEN;
/// `POOL_FLAG_NON_PAGED` (wdm.h; not generated by wdk-sys).
const POOL_FLAG_NON_PAGED: u64 = 0x0000_0000_0000_0040;
/// Pool tag `'BtpA'`.
const POOL_TAG: ULONG = u32::from_le_bytes(*b"ApTB");

/// Why the original request was forwarded unchanged.
#[derive(Clone, Copy)]
enum PassThrough {
    NotPassive,
    NoBuffers,
    NoMemory,
    SearchFailed(NTSTATUS),
    BadResponse,
    Augment(SdpAugmentError),
}

impl PassThrough {
    const fn reason(self) -> &'static str {
        match self {
            Self::NotPassive => "not at PASSIVE_LEVEL",
            Self::NoBuffers => "request buffers unavailable",
            Self::NoMemory => "no scratch memory",
            Self::SearchFailed(_) => "lookahead search failed",
            Self::BadResponse => "lookahead response incomplete or too large",
            Self::Augment(SdpAugmentError::Malformed) => "attribute list malformed",
            Self::Augment(SdpAugmentError::NoReportDescriptor) => "no report descriptor",
            Self::Augment(SdpAugmentError::Unexpected) => "descriptor already declares the reports",
            Self::Augment(SdpAugmentError::OutputTooSmall) => "augmented list too large",
        }
    }
}

/// Two nonpaged scratch buffers of [`SCRATCH_LEN`] bytes, freed on drop.
struct Scratch(*mut u8);

impl Scratch {
    fn allocate() -> Option<Self> {
        // SAFETY: callable at <= DISPATCH_LEVEL; a nonpaged allocation with our tag.
        let p = unsafe { ExAllocatePool2(POOL_FLAG_NON_PAGED, 2 * SCRATCH_LEN as u64, POOL_TAG) };
        (!p.is_null()).then_some(Self(p.cast::<u8>()))
    }

    /// The lookahead response buffer and the augmented-stream buffer.
    const fn split(&mut self) -> (&mut [u8], &mut [u8]) {
        // SAFETY: the allocation holds 2 * SCRATCH_LEN bytes (ExAllocatePool2 zero-fills it) and is
        // only reachable through `self`.
        let all = unsafe { core::slice::from_raw_parts_mut(self.0, 2 * SCRATCH_LEN) };
        all.split_at_mut(SCRATCH_LEN)
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        // SAFETY: allocated by `allocate` with the same tag, freed once.
        unsafe { ExFreePoolWithTag(self.0.cast::<c_void>(), POOL_TAG) };
    }
}

fn read_u32(bytes: &[u8], at: usize) -> Option<usize> {
    let field = bytes.get(at..at + 4)?;
    let value = u32::from_le_bytes(field.try_into().ok()?);
    usize::try_from(value).ok()
}

fn write_u32(bytes: &mut [u8], at: usize, value: usize) -> Option<()> {
    let value = u32::try_from(value).ok()?;
    bytes.get_mut(at..at + 4)?.copy_from_slice(&value.to_le_bytes());
    Some(())
}

/// Answers an `IOCTL_BTH_SDP_SERVICE_ATTRIBUTE_SEARCH` request with the augmented attribute list.
///
/// Returns `true` when it completed the request, `false` when the caller must forward it unchanged.
///
/// # Safety
/// `request` is an `IOCTL_BTH_SDP_SERVICE_ATTRIBUTE_SEARCH` request presented to this driver, and
/// `device` its device.
pub(crate) unsafe fn serve(device: WDFDEVICE, request: WDFREQUEST) -> bool {
    // SAFETY: forwarded.
    match unsafe { try_serve(device, request) } {
        Ok(()) => true,
        Err(why) => {
            let status = if let PassThrough::SearchFailed(status) = why {
                status
            } else {
                STATUS_SUCCESS
            };
            tlg::write_event!(
                PROVIDER,
                "SdpPassThrough",
                level(Warning),
                keyword(KW_SDP),
                str8("Reason", why.reason()),
                win_ntstatus("Status", &status)
            );
            false
        }
    }
}

/// # Safety
/// As [`serve`].
unsafe fn try_serve(device: WDFDEVICE, request: WDFREQUEST) -> Result<(), PassThrough> {
    // SAFETY: no preconditions.
    if u32::from(unsafe { KeGetCurrentIrql() }) != PASSIVE_LEVEL {
        return Err(PassThrough::NotPassive);
    }
    let (mut input, mut input_len): (PVOID, usize) = (null_mut(), 0);
    let (mut output, mut output_len): (PVOID, usize) = (null_mut(), 0);
    // SAFETY: a METHOD_BUFFERED request this driver owns; the input and output share the system
    // buffer, so the input is consumed (sent down) before the output is written.
    let got = unsafe {
        NT_SUCCESS(call_unsafe_wdf_function_binding!(
            WdfRequestRetrieveInputBuffer,
            request,
            1,
            &raw mut input,
            &raw mut input_len
        )) && NT_SUCCESS(call_unsafe_wdf_function_binding!(
            WdfRequestRetrieveOutputBuffer,
            request,
            STREAM_HEADER_LEN,
            &raw mut output,
            &raw mut output_len
        ))
    };
    if !got || input.is_null() || output.is_null() {
        return Err(PassThrough::NoBuffers);
    }
    let input_len = ULONG::try_from(input_len)
        .ok()
        .ok_or(PassThrough::NoBuffers)?;
    let mut scratch = Scratch::allocate().ok_or(PassThrough::NoMemory)?;
    let (lookahead, augmented) = scratch.split();

    // The same search, into our buffer.
    let mut input_desc = memory_descriptor_init_buffer(input, input_len);
    let mut output_desc =
        memory_descriptor_init_buffer(lookahead.as_mut_ptr().cast::<c_void>(), SCRATCH_LEN as ULONG);
    let mut options = sync_send_options(0);
    let mut returned: ULONG_PTR = 0;
    // SAFETY: PASSIVE_LEVEL; our device's default target; descriptors over live buffers.
    let status = unsafe {
        let target = call_unsafe_wdf_function_binding!(WdfDeviceGetIoTarget, device);
        call_unsafe_wdf_function_binding!(
            WdfIoTargetSendIoctlSynchronously,
            target,
            null_mut(),
            IOCTL_SDP_SERVICE_ATTRIBUTE_SEARCH,
            &raw mut input_desc,
            &raw mut output_desc,
            &raw mut options,
            &raw mut returned
        )
    };
    if !NT_SUCCESS(status) {
        return Err(PassThrough::SearchFailed(status));
    }
    let returned = usize::try_from(returned).unwrap_or(0).min(SCRATCH_LEN);
    let required = read_u32(lookahead, 0).ok_or(PassThrough::BadResponse)?;
    let response = read_u32(lookahead, 4).ok_or(PassThrough::BadResponse)?;
    if response == 0 || response != required || STREAM_HEADER_LEN + response > returned {
        return Err(PassThrough::BadResponse);
    }
    let stream = lookahead
        .get(STREAM_HEADER_LEN..STREAM_HEADER_LEN + response)
        .ok_or(PassThrough::BadResponse)?;
    let new_len = augment_sdp_attribute_list(stream, augmented).map_err(PassThrough::Augment)?;
    let new_stream = augmented.get(..new_len).ok_or(PassThrough::BadResponse)?;

    // Answer like the stack does: the full stream when it fits (Information = 8 + size), else
    // only requiredSize (responseSize 0, Information = the buffer size).
    // SAFETY: the request's output buffer holds `output_len` bytes and is ours until completion.
    let out = unsafe { core::slice::from_raw_parts_mut(output.cast::<u8>(), output_len) };
    write_u32(out, 0, new_len).ok_or(PassThrough::BadResponse)?;
    let information = if output_len >= STREAM_HEADER_LEN + new_len {
        write_u32(out, 4, new_len).ok_or(PassThrough::BadResponse)?;
        out.get_mut(STREAM_HEADER_LEN..STREAM_HEADER_LEN + new_len)
            .ok_or(PassThrough::BadResponse)?
            .copy_from_slice(new_stream);
        STREAM_HEADER_LEN + new_len
    } else {
        write_u32(out, 4, 0).ok_or(PassThrough::BadResponse)?;
        let room = output_len - STREAM_HEADER_LEN;
        if let (Some(dst), Some(src)) = (
            out.get_mut(STREAM_HEADER_LEN..),
            new_stream.get(..room),
        ) {
            dst.copy_from_slice(src);
        }
        output_len
    };
    tlg::write_event!(
        PROVIDER,
        "SdpAugmented",
        level(Informational),
        keyword(KW_SDP),
        u64("OriginalSize", &(response as u64)),
        u64("AugmentedSize", &(new_len as u64)),
        u64("OutputLength", &(output_len as u64)),
        u64("Information", &(information as u64))
    );
    // SAFETY: completed exactly once, by this driver.
    unsafe {
        call_unsafe_wdf_function_binding!(
            WdfRequestCompleteWithInformation,
            request,
            STATUS_SUCCESS,
            information as ULONG_PTR
        );
    }
    Ok(())
}

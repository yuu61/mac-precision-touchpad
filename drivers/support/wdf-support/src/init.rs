/// `WDF_TIMEOUT_TO_SEC`: 100 ns units per second.
pub const WDF_TIMEOUT_TO_SEC: LONGLONG = 10 * 1000 * 1000;
/// `WDF_TIMEOUT_TO_MS`: 100 ns units per millisecond.
pub const WDF_TIMEOUT_TO_MS: LONGLONG = 10 * 1000;
/// `WDF_TIMEOUT_TO_US`: 100 ns units per microsecond.
pub const WDF_TIMEOUT_TO_US: LONGLONG = 10;

/// `Time * -1 * Unit` evaluated exactly as C does for a `ULONGLONG Time`:
/// `-1` and `Unit` are converted to `ULONGLONG`, the products wrap modulo 2^64,
/// and the result is converted to `LONGLONG` (two's complement on MSVC).
const fn rel_timeout(time: u64, unit: LONGLONG) -> LONGLONG {
    // `u64::MAX` is `(ULONGLONG)-1`; `unit as u64` is the (positive) unit.
    time.wrapping_mul(u64::MAX).wrapping_mul(unit as u64) as LONGLONG
}

/// `WDF_REL_TIMEOUT_IN_SEC(Time)`: relative timeout (negative 100 ns units).
#[doc(alias = "WDF_REL_TIMEOUT_IN_SEC")]
#[must_use]
pub const fn rel_timeout_in_sec(time: u64) -> LONGLONG {
    rel_timeout(time, WDF_TIMEOUT_TO_SEC)
}

/// `WDF_REL_TIMEOUT_IN_MS(Time)`: relative timeout (negative 100 ns units).
#[doc(alias = "WDF_REL_TIMEOUT_IN_MS")]
#[must_use]
pub const fn rel_timeout_in_ms(time: u64) -> LONGLONG {
    rel_timeout(time, WDF_TIMEOUT_TO_MS)
}

/// `WDF_REL_TIMEOUT_IN_US(Time)`: relative timeout (negative 100 ns units).
#[doc(alias = "WDF_REL_TIMEOUT_IN_US")]
#[must_use]
pub const fn rel_timeout_in_us(time: u64) -> LONGLONG {
    rel_timeout(time, WDF_TIMEOUT_TO_US)
}

const _: () = {
    assert!(SYNC_IO_TIMEOUT == -50_000_000);
    assert!(rel_timeout_in_sec(1) == -10_000_000);
    assert!(rel_timeout_in_sec(3) == -30_000_000);
    assert!(rel_timeout_in_ms(5) == -50_000);
    assert!(rel_timeout_in_us(250) == -2_500);
    assert!(rel_timeout_in_ms(0) == 0);
};


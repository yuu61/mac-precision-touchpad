/// `WDF_OBJECT_ATTRIBUTES_SET_CONTEXT_TYPE(&attributes, T)`:
/// `attributes->ContextTypeInfo = WDF_GET_CONTEXT_TYPE_INFO(T)->UniqueType`.
///
/// `context_type` is the static generated by [`crate::declare_context_type!`].
#[doc(alias = "WDF_OBJECT_ATTRIBUTES_SET_CONTEXT_TYPE")]
pub const fn object_attributes_set_context_type(
    attributes: &mut WDF_OBJECT_ATTRIBUTES,
    context_type: &'static ContextTypeInfo,
) {
    attributes.ContextTypeInfo = context_type.unique_type();
}

/// `WDF_OBJECT_ATTRIBUTES_INIT_CONTEXT_TYPE(&attributes, T)`:
/// [`object_attributes_init`] followed by [`object_attributes_set_context_type`].
#[doc(alias = "WDF_OBJECT_ATTRIBUTES_INIT_CONTEXT_TYPE")]
#[must_use]
pub fn object_attributes_init_context_type(
    context_type: &'static ContextTypeInfo,
) -> WDF_OBJECT_ATTRIBUTES {
    let mut attributes = object_attributes_init();
    object_attributes_set_context_type(&mut attributes, context_type);
    attributes
}


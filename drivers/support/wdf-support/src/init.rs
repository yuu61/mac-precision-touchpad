fn usb_control_setup_packet(
    direction: WDF_USB_BMREQUEST_DIRECTION,
    request_type: WDF_USB_BMREQUEST_TYPE,
    recipient: WDF_USB_BMREQUEST_RECIPIENT,
    request: BYTE,
    value: USHORT,
    index: USHORT,
) -> WDF_USB_CONTROL_SETUP_PACKET {
    let mut packet = WDF_USB_CONTROL_SETUP_PACKET::default();
    // SAFETY: `packet` is a zero-initialized local; `Packet` is the active
    // (structured) view of the 8-byte setup packet union and every field is
    // plain data, so borrowing it to set the bitfields is sound.
    let setup = unsafe { &mut packet.Packet };
    // The C code casts the enum values with `(BYTE)`; `as` truncates the same
    // way (the values are 0..=3 anyway).
    // SAFETY: `bm` is a union of `Request` (bitfields) and `Byte`, both views of
    // the same zeroed byte; borrowing the bitfield view is sound.
    let bm = unsafe { &mut setup.bm.Request };
    bm.set_Dir(direction as BYTE);
    bm.set_Type(request_type as BYTE);
    bm.set_Recipient(recipient as BYTE);
    setup.bRequest = request;
    setup.wValue.Value = value;
    setup.wIndex.Value = index;
    // Packet.wLength is set by the formatting function (as in C).
    packet
}


/// `sizeof(T)` as the `ULONG` stored in a WDF structure's `Size` field.
///
/// Compile-time checked to fit in a `ULONG`.
#[must_use]
#[inline]
pub const fn wdf_size<T>() -> ULONG {
    const { assert!(size_of::<T>() <= ULONG::MAX as usize) };
    // Lossless: checked by the const assertion above.
    size_of::<T>() as ULONG
}

